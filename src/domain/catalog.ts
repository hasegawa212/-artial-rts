/** 台帳の不整合を文字列で返す（空配列 = 問題なし）。 */
export function validateCatalog(apps: readonly AppEntry[]): string[] {
  const errors: string[] = [];
  const seen = new Set<string>();
  for (const a of apps) {
    if (seen.has(a.id)) errors.push(`duplicate id: ${a.id}`);
    seen.add(a.id);
    if (!/^[a-z0-9-]+$/.test(a.id)) errors.push(`${a.id}: id must be kebab-case`);
    if (a.urlStatus === "unknown" && a.url) errors.push(`${a.id}: unknown status must not carry a url`);
    if (a.urlStatus !== "unknown" && !a.url) errors.push(`${a.id}: ${a.urlStatus} status but no url`);
    if (a.url && !isSafeUrl(a.url)) errors.push(`${a.id}: url must be https without credentials`);
    if (a.confidential && a.visibility === "member") errors.push(`${a.id}: confidential app visible to members`);
  }
  return errors;
}

export function visibleApps<T extends AppEntry>(apps: readonly T[], user: { role: Role } | null | undefined): T[] {
  return apps.filter((a) => canSeeApp(user, a));
}

export function appsByCategory<T extends AppEntry>(apps: readonly T[]) {
  return CATEGORIES.map((category) => ({ category, apps: apps.filter((a) => a.category === category.id) })).filter(
    (g) => g.apps.length > 0,
  );
}

export function categoryOf(id: CategoryId) {
  return CATEGORIES.find((c) => c.id === id)!;
}
